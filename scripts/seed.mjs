const uri = process.env.MONGODB_URI;
if (!uri) {
  console.error("MONGODB_URI is not set. Add it to .env.local before seeding.");
  process.exit(1);
}

try {
  await mongoose.connect(uri, { bufferCommands: false });
  const temples = mongoose.connection.collection("temples");
  const results = await Promise.all(
    sampleTemples.map((temple) =>
      temples.updateOne(
        { slug: temple.slug },
        { $setOnInsert: { ...temple, createdAt: new Date(), updatedAt: new Date() } },
        { upsert: true },
      ),
    ),
  );
  const inserted = results.filter((result) => result.upsertedCount > 0).length;
  console.log(`Temple seed complete: ${inserted} new guides added; existing records were left unchanged.`);
} catch (error) {
  const message = error instanceof Error ? error.message : "Unknown database error.";
  console.error(`Unable to seed temple guides: ${message.replace(uri, "[MONGODB_URI]")}`);
  process.exitCode = 1;
} finally {
  await mongoose.disconnect();
}
